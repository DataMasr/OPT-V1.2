const LANG_STORAGE_KEY = 'cyperopt.lang';

const Lang = {
  current: 'ar',
  listeners: [],
  locale() {
    // Arabic text with Latin digits, as used across the app
    return this.current === 'ar' ? 'ar-EG-u-nu-latn' : 'en-US';
  }
};

function t(key, vars) {
  let s = I18N[Lang.current][key];
  if (s === undefined) s = I18N.en[key];
  if (s === undefined) s = key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
  return s;
}

const normalizeText = s => s.replace(/\s+/g, ' ').trim();

// English for tagged elements comes from the markup itself
function captureDefaultStrings() {
  const keep = (key, value) => {
    if (key && I18N.en[key] === undefined) I18N.en[key] = value;
  };
  document.querySelectorAll('[data-i18n]').forEach(el => keep(el.dataset.i18n, normalizeText(el.textContent)));
  document.querySelectorAll('[data-i18n-html]').forEach(el => keep(el.dataset.i18nHtml, normalizeText(el.innerHTML)));
  document.querySelectorAll('[data-i18n-title]').forEach(el => keep(el.dataset.i18nTitle, el.getAttribute('title') || ''));
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => keep(el.dataset.i18nPlaceholder, el.getAttribute('placeholder') || ''));
}

function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}

function setLanguage(lang, silent) {
  if (!I18N[lang]) lang = 'ar';
  Lang.current = lang;

  const root = document.documentElement;
  root.lang = lang;
  root.dir = lang === 'ar' ? 'rtl' : 'ltr';
  try { localStorage.setItem(LANG_STORAGE_KEY, lang); } catch (e) { }

  applyStaticTranslations();
  if (!silent) Lang.listeners.forEach(fn => fn(lang));
}

function onLanguageChange(fn) {
  Lang.listeners.push(fn);
}

// Runs before app.js so the first paint is already in the right language
(function initI18n() {
  captureDefaultStrings();
  let saved = null;
  try { saved = localStorage.getItem(LANG_STORAGE_KEY); } catch (e) { }
  setLanguage(saved === 'en' ? 'en' : 'ar', true);
  document.documentElement.classList.remove('i18n-pending');
})();
